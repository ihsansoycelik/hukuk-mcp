"""Python <-> TypeScript analyser parity.

The fixture is generated by Node from the real corpus (see
``gen_parity_fixture.py``); this test only compares, it never generates.
100% of words must produce the same tokens and ``kok``.
"""
from __future__ import annotations

import json
import unittest
from pathlib import Path

from pipeline.trtext_py import analyze, fold_normalized, stem_folded, tr_fold, tr_lower

FIXTURE = Path(__file__).resolve().parents[2] / "data" / "build" / "parity_words.json"


class TestParity(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not FIXTURE.exists():
            raise unittest.SkipTest(
                "parity fixture missing; run pipeline/test/gen_parity_fixture.py")
        cls.payload = json.loads(FIXTURE.read_text(encoding="utf-8"))
        cls.expected = cls.payload["expected"]

    def test_fixture_size(self) -> None:
        self.assertGreaterEqual(len(self.expected), 200)

    def test_tokens_identical(self) -> None:
        failures = []
        for exp in self.expected:
            got = analyze(exp["word"])
            if got.tokens != exp["tokens"]:
                failures.append((exp["word"], exp["tokens"], got.tokens))
        self.assertEqual(failures, [], f"{len(failures)} parity failures: {failures[:10]}")

    def test_kok_identical(self) -> None:
        failures = []
        for exp in self.expected:
            got = analyze(exp["word"]).kok
            if got != exp["kok"]:
                failures.append((exp["word"], exp["kok"], got))
        self.assertEqual(failures, [], f"{len(failures)} kok failures: {failures[:10]}")

    def test_stem_of_folded_word(self) -> None:
        for exp in self.expected:
            folded = fold_normalized(exp["word"])
            if not folded or " " in folded or len(exp["tokens"]) != 1:
                continue
            self.assertEqual(stem_folded(folded), exp["tokens"][0], exp["word"])

    def test_casing_and_folding(self) -> None:
        self.assertEqual(tr_lower("IĞDIR İSTANBUL"), "ığdır istanbul")
        self.assertEqual(tr_fold("çğıöşüâîû"), "cgiosuaiu")
        self.assertEqual(analyze("Gizli ayıplı malın bedel iadesi").kok,
                         "gizli ayipl mal bedel iade")


if __name__ == "__main__":
    unittest.main()
