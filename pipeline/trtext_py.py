"""Python port of ``packages/tr-text/src/index.ts`` (@hukuk/tr-text).

The build pipeline and the query path must fold text to *exactly* the same FTS
keys, so this file is a line-for-line port of the TypeScript analyser:

  normalize()   NFKC -> Turkish lowercase -> punctuation cleanup
  trFold()      strip Turkish diacritics (ASCII key space)
  stemFolded()  conservative two-pass suffix stripper
  analyze()     folded + stemmed tokens, stopwords removed -> ``kok``

Do not "improve" the algorithm here: any divergence from the TS source breaks
the index/query contract. ``pipeline/test/test_trtext.test.py`` enforces
100% parity against a fixture generated by Node from the real corpus.
"""
from __future__ import annotations

import re
import unicodedata

TR_LOWER = {
    "I": "ı",
    "İ": "i",
    "Ş": "ş",
    "Ğ": "ğ",
    "Ü": "ü",
    "Ö": "ö",
    "Ç": "ç",
}

FOLD = {
    "ç": "c",
    "ğ": "g",
    "ı": "i",
    "ö": "o",
    "ş": "s",
    "ü": "u",
    "â": "a",
    "î": "i",
    "û": "u",
    "ê": "e",
    "ô": "o",
    "ä": "a",
    "ë": "e",
    "ï": "i",
    "ñ": "n",
}

_WS = re.compile(r"\s+")
_QUOTES = re.compile(r"[’‘`´]")
_APOS_EDGE = re.compile(r"^'+|'+$")
_DIGITS = re.compile(r"^\d+$")


def tr_lower(input: str) -> str:
    """Locale-correct Turkish lowercase (I -> ı, İ -> i)."""
    return "".join(TR_LOWER.get(ch, ch.lower()) for ch in input)


def tr_fold(input: str) -> str:
    """Strip diacritics so the FTS key space is ASCII."""
    return "".join(FOLD.get(ch, ch) for ch in input)


def _is_letter_or_digit(ch: str) -> bool:
    # JS \p{L} / \p{N}: unicode general categories L* and N*.
    return unicodedata.category(ch)[0] in ("L", "N")


def normalize(input: str) -> str:
    """Full normalisation: NFKC, Turkish lowercasing, diacritic folding, punctuation cleanup."""
    s = _WS.sub(" ", unicodedata.normalize("NFKC", input)).strip()
    s = tr_lower(s)
    s = _QUOTES.sub("'", s)
    # keep letters, digits, apostrophe and whitespace; every other char -> space
    out = []
    for ch in s:
        if ch == "'" or ch.isspace() or _is_letter_or_digit(ch):
            out.append(ch)
        else:
            out.append(" ")
    s = "".join(out)
    s = _WS.sub(" ", s).strip()
    return s


def fold_normalized(input: str) -> str:
    return tr_fold(normalize(input))


