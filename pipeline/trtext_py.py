class Analyzed:
    __slots__ = ("kok", "tokens", "words")

    def __init__(self, kok: str, tokens: list[str], words: list[str]) -> None:
        self.kok = kok
        self.tokens = tokens
        self.words = words


def analyze(input: str) -> Analyzed:
    norm = normalize(input)
    words = [w for w in norm.split(" ") if w]
    tokens: list[str] = []
    for w in words:
        folded = _APOS_EDGE.sub("", tr_fold(w))
        if not folded:
            continue
        if folded in STOPWORDS:
            continue
        if _DIGITS.match(folded):
            tokens.append(folded)
            continue
        if len(folded) < 2:
            continue
        tokens.append(stem_folded(folded))
    return Analyzed(" ".join(tokens), tokens, words)


def fts_key(input: str) -> str:
    return analyze(input).kok


# ---------------------------------------------------------------------------
# character n-gram vectors (port of ngramVector / vectorToJSON)
# ---------------------------------------------------------------------------

def _ngrams(word: str, n: int = 3) -> list[str]:
    padded = f"^{word}$"
    return [padded[i : i + n] for i in range(0, len(padded) - n + 1)]


def ngram_vector(input: str, n: int = 3) -> dict[str, float]:
    """Build a normalised char n-gram vector from text (same as TS)."""
    words = analyze(input).words
    counts: dict[str, int] = {}
    for w in words:
        for g in _ngrams(w, n):
            counts[g] = counts.get(g, 0) + 1
    norm = sum(v * v for v in counts.values()) ** 0.5 or 1.0
    return {k: v / norm for k, v in counts.items()}


def vector_to_json(vec: dict[str, float]) -> str:
    import json

    return json.dumps(vec, ensure_ascii=False, separators=(",", ":"))
