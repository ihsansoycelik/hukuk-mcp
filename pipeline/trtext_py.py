# JS Array#sort on length is stable (ES2019); Python's sorted is stable too.
SORTED_NOUN = sorted(NOUN_SUFFIXES, key=len, reverse=True)
SORTED_VERB_STRONG = sorted(VERB_STRONG, key=len, reverse=True)


def _strip_with(word: str, inventory: list[str]) -> str | None:
    for suf in inventory:
        if not word.endswith(suf):
            continue
        rest = len(word) - len(suf)
        if len(suf) == 1:
            if len(word) >= 6 and rest >= 4:
                return word[:rest]
            continue
        if rest >= 3:
            return word[:rest]
    return None


def stem_folded(word: str, permit_verb: bool = True) -> str:
    if len(word) <= 3:
        return word
    w = word
    for _pass in range(2):
        noun = _strip_with(w, SORTED_NOUN)
        if noun is not None:
            w = noun
            continue
        if not permit_verb or len(w) < 5:
            break
        strong = _strip_with(w, SORTED_VERB_STRONG)
        if strong is not None:
            w = strong
            continue
        break
    return w if len(w) >= 2 else word


